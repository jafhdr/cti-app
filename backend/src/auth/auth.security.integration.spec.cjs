const assert = require('node:assert/strict');
const test = require('node:test');
const { randomUUID } = require('node:crypto');
const { mkdirSync } = require('node:fs');
const { resolve } = require('node:path');
const { Test } = require('@nestjs/testing');
const { ConfigModule } = require('@nestjs/config');
const { ValidationPipe } = require('@nestjs/common');
const cookieParser = require('cookie-parser');
const { PrismaClient } = require('@prisma/client');
const { SMTPServer } = require('smtp-server');
const bcrypt = require('bcrypt');
const { chromium, expect } = require('../../../frontend/node_modules/@playwright/test');
const { AuthModule } = require('../../dist/src/auth/auth.module');

test('auth sessions, replay, password reset and local SMTP delivery', { timeout: 120000 }, async () => {
  const messages = [];
  const smtp = new SMTPServer({ authOptional: true, disabledCommands: ['STARTTLS'], onData(stream, session, callback) {
    const chunks = [];
    stream.on('data', chunk => chunks.push(chunk));
    stream.on('end', () => { messages.push(Buffer.concat(chunks).toString()); callback(); });
  } });
  await new Promise((resolve, reject) => smtp.listen(0, '127.0.0.1', error => error ? reject(error) : resolve()));
  const oldEnv = Object.fromEntries(['SMTP_HOST', 'SMTP_PORT', 'SMTP_FROM', 'FRONTEND_URL'].map(key => [key, process.env[key]]));
  Object.assign(process.env, { SMTP_HOST: '127.0.0.1', SMTP_PORT: String(smtp.server.address().port), SMTP_FROM: 'security@example.test', FRONTEND_URL: 'http://localhost:3000' });
  const moduleRef = await Test.createTestingModule({ imports: [ConfigModule.forRoot({ isGlobal: true }), AuthModule] }).compile();
  const app = moduleRef.createNestApplication({ logger: false });
  app.use(cookieParser()); app.enableCors({ origin: true, credentials: true }); app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true }));
  const prisma = new PrismaClient();
  const suffix = randomUUID();
  let tenantId; let userId; let browser;
  try {
    await app.listen(0, '127.0.0.1');
    const api = `http://localhost:${app.getHttpServer().address().port}`;
    const tenant = await prisma.tenant.create({ data: { name: 'Auth QA', slug: `auth-qa-${suffix}` } }); tenantId = tenant.id;
    const email = `auth-qa-${suffix}@example.test`;
    const oldPassword = `Old-${suffix}`; const newPassword = `New-${suffix}`;
    const user = await prisma.user.create({ data: { name: 'Auth QA', email, passwordHash: await bcrypt.hash(oldPassword, 4), role: 'ADMIN', tenantId } }); userId = user.id;
    const send = async (path, method = 'GET', body, cookie = '') => fetch(api + path, { method, headers: { 'Content-Type': 'application/json', Cookie: cookie }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const login = async password => send('/auth/login', 'POST', { email, password });
    const cookie = response => response.headers.getSetCookie().map(value => value.split(';')[0]).join('; ');
    const first = await login(oldPassword); assert.equal(first.status, 201);
    const firstCookies = cookie(first);
    assert.equal((await send('/auth/me', 'GET', undefined, firstCookies)).status, 200);
    assert.equal((await send('/auth/logout', 'POST', undefined, firstCookies)).status, 201);
    const logoutEvents = await prisma.auditLog.findMany({ where: { userId, tenantId, action: 'LOGOUT' } });
    assert.equal(logoutEvents.length, 1);
    assert.equal(logoutEvents[0].metadata.sessionId.length > 0, true);
    assert.equal(/token|password|secret/i.test(JSON.stringify(logoutEvents[0].metadata)), false);
    assert.equal((await send('/auth/logout', 'POST', undefined, firstCookies)).status, 201);
    assert.equal(await prisma.auditLog.count({ where: { userId, tenantId, action: 'LOGOUT' } }), 1);
    assert.equal((await send('/auth/me', 'GET', undefined, firstCookies)).status, 401);
    assert.equal((await send('/auth/refresh', 'POST', undefined, firstCookies)).status, 401);
    const second = await login(oldPassword); assert.equal(second.status, 201);
    const secondCookies = cookie(second);
    const rotated = await send('/auth/refresh', 'POST', undefined, secondCookies); assert.equal(rotated.status, 201);
    const rotatedCookies = cookie(rotated);
    assert.equal((await send('/auth/refresh', 'POST', undefined, secondCookies)).status, 401);
    assert.equal((await send('/auth/me', 'GET', undefined, rotatedCookies)).status, 200);
    assert.equal((await send('/auth/logout', 'POST', undefined, secondCookies)).status, 201);
    assert.equal((await send('/auth/me', 'GET', undefined, rotatedCookies)).status, 401);
    assert.equal((await send('/auth/refresh', 'POST', undefined, rotatedCookies)).status, 401);
    const third = await login(oldPassword); assert.equal(third.status, 201);
    const thirdCookies = cookie(third);
    const fourth = await login(oldPassword); assert.equal(fourth.status, 201);
    const fourthCookies = cookie(fourth);
    const concurrent = await Promise.all([send('/auth/refresh', 'POST', undefined, thirdCookies), send('/auth/refresh', 'POST', undefined, thirdCookies)]);
    assert.deepEqual(concurrent.map(response => response.status).sort(), [201, 401]);
    const concurrentCookies = cookie(concurrent.find(response => response.status === 201));
    const unknown = await send('/auth/forgot-password', 'POST', { email: `missing-${suffix}@example.test` });
    const forgot = await send('/auth/forgot-password', 'POST', { email });
    assert.equal(unknown.status, forgot.status); assert.deepEqual(await unknown.json(), await forgot.json());
    assert.equal(messages.length, 1);
    const rawToken = messages[0].replace(/=\r?\n/g, '').replace(/=3D/gi, '=').match(/token=([a-f0-9]{64})/)?.[1]; assert.ok(rawToken);
    const stored = await prisma.passwordResetToken.findFirst({ where: { userId, usedAt: null } });
    assert.ok(stored); assert.notEqual(stored.tokenHash, rawToken);
    await prisma.passwordResetToken.update({ where: { id: stored.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    assert.equal((await send('/auth/reset-password', 'POST', { token: rawToken, password: newPassword })).status, 400);
    await prisma.passwordResetToken.update({ where: { id: stored.id }, data: { expiresAt: new Date(Date.now() + 60000) } });
    assert.equal((await send('/auth/reset-password', 'POST', { token: rawToken, password: newPassword })).status, 201);
    assert.equal((await send('/auth/reset-password', 'POST', { token: rawToken, password: newPassword })).status, 400);
    for (const stale of [secondCookies, rotatedCookies, thirdCookies, concurrentCookies, fourthCookies]) {
      assert.equal((await send('/auth/me', 'GET', undefined, stale)).status, 401);
      assert.equal((await send('/auth/refresh', 'POST', undefined, stale)).status, 401);
    }
    assert.equal((await login(oldPassword)).status, 401);
    const fresh = await login(newPassword); assert.equal(fresh.status, 201);
    assert.equal((await send('/auth/me', 'GET', undefined, cookie(fresh))).status, 200);
    const evidence = resolve('../.omo/evidence/auth-v1-remediation'); mkdirSync(evidence, { recursive: true });
    browser = await chromium.launch({ headless: true });
    const context = await browser.newContext();
    const page = await context.newPage();
    await page.route('http://localhost:3001/**', route => route.continue({ url: api + new URL(route.request().url()).pathname + new URL(route.request().url()).search }));
    for (const width of [375, 768, 1280]) {
      await page.setViewportSize({ width, height: 900 });
      await page.goto('http://localhost:3000/forgot-password');
      await expect(page.getByRole('heading', { name: 'Lupa password?' })).toBeVisible();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: `${evidence}/forgot-${width}.png`, fullPage: true });
      await page.goto('http://localhost:3000/reset-password');
      await expect(page.getByRole('heading', { name: 'Reset password' })).toBeVisible();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
      await page.screenshot({ path: `${evidence}/reset-${width}.png`, fullPage: true });
    }
    await page.goto('http://localhost:3000/reset-password?token=' + rawToken);
    await page.getByLabel('Password baru').fill(newPassword);
    await page.getByLabel('Konfirmasi password').fill(newPassword);
    await page.getByRole('button', { name: 'Simpan password' }).click();
    await expect(page.locator('.auth-card .error')).toContainText('tidak valid');
    await page.goto('http://localhost:3000/login');
    await page.getByLabel('Email address').fill(email);
    await page.getByLabel('Password', { exact: true }).fill(newPassword);
    await page.getByRole('button', { name: 'Sign In' }).click();
    await expect(page).toHaveURL(/\/dashboard/, { timeout: 5000 });
    await page.goto('http://localhost:3000/forgot-password');
    await page.locator('input[type=email]').fill(email);
    await page.getByRole('button', { name: 'Kirim link reset' }).click();
    await expect(page.locator('.success')).toContainText('dikirim');
    assert.equal(messages.length, 2);
    const browserToken = messages[1].replace(/=\r?\n/g, '').replace(/=3D/gi, '=').match(/token=([a-f0-9]{64})/)?.[1]; assert.ok(browserToken);
    await page.goto('http://localhost:3000/reset-password?token=' + browserToken);
    const browserPassword = `Browser-${suffix}`;
    await page.getByLabel('Password baru').fill(browserPassword);
    await page.getByLabel('Konfirmasi password').fill(browserPassword);
    await page.getByRole('button', { name: 'Simpan password' }).click();
    await expect(page.locator('.success')).toContainText('berhasil');
    await expect(page).toHaveURL(/\/login/, { timeout: 10000 });
    await page.getByLabel('Email address').fill(email);
    await page.getByLabel('Password', { exact: true }).fill(browserPassword);
    await page.getByRole('button', { name: 'Sign In' }).click();
    await expect(page).toHaveURL(/\/dashboard/, { timeout: 5000 });
    assert.equal(await page.evaluate(async () => (await fetch('http://localhost:3001/auth/me', { credentials: 'include' })).status), 200);
    assert.equal(await page.evaluate(async () => (await fetch('http://localhost:3001/auth/logout', { method: 'POST', credentials: 'include' })).status), 201);
    assert.equal(await page.evaluate(async () => (await fetch('http://localhost:3001/auth/me', { credentials: 'include' })).status), 401);
    await page.goto('http://localhost:3000/dashboard');
    await expect(page).toHaveURL(/\/login/, { timeout: 10000 });
    await context.close(); await browser.close(); browser = undefined;
    for (let index = 0; index < 3; index++) await send('/auth/forgot-password', 'POST', { email });
    assert.equal(messages.length, 3, 'hourly limit allows three reset emails');
    await Promise.all(Array.from({ length: 5 }, () => send('/auth/forgot-password', 'POST', { email })));
    assert.equal(messages.length, 3, 'concurrent requests cannot bypass the hourly limit');
    await prisma.passwordResetToken.updateMany({ where: { userId }, data: { createdAt: new Date(Date.now() - 2 * 60 * 60 * 1000) } });
    process.env.SMTP_PORT = '1';
    const failedKnown = await send('/auth/forgot-password', 'POST', { email });
    const failedUnknown = await send('/auth/forgot-password', 'POST', { email: `missing-${suffix}@example.test` });
    assert.equal(failedKnown.status, failedUnknown.status);
    assert.deepEqual(await failedKnown.json(), await failedUnknown.json());
    assert.equal((await prisma.passwordResetToken.findFirst({ where: { userId }, orderBy: { createdAt: 'desc' } })).usedAt !== null, true);
    delete process.env.SMTP_HOST;
    assert.equal((await send('/auth/forgot-password', 'POST', { email })).status, 503);
    assert.equal((await send('/auth/forgot-password', 'POST', { email: `missing-${suffix}@example.test` })).status, 503);
  } finally {
    if (browser) await browser.close();
    await app.close();
    await prisma.auditLog.deleteMany({ where: { userId } });
    await prisma.passwordResetToken.deleteMany({ where: { userId } });
    await prisma.user.deleteMany({ where: { id: userId } });
    await prisma.tenant.deleteMany({ where: { id: tenantId } });
    await prisma.$disconnect();
    await new Promise(resolve => smtp.close(resolve));
    for (const [key, value] of Object.entries(oldEnv)) { if (value === undefined) delete process.env[key]; else process.env[key] = value; }
  }
});

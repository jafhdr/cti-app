require('reflect-metadata');
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { randomUUID } = require('node:crypto');
const { readFileSync } = require('node:fs');
const { Test } = require('@nestjs/testing');
const { ConfigModule } = require('@nestjs/config');
const { PrismaClient } = require('@prisma/client');
const { AuthModule } = require('../../dist/src/auth/auth.module');
const { PlaybookModule } = require('../../dist/src/playbooks/playbook.module');
const { createAccessToken } = require('../auth/integration-session.cjs');

test('Given a tenant correlation alert, when separate analysts approve, then only a QA simulation is verified', { timeout: 90000 }, async () => {
  assert.match(new URL(process.env.DATABASE_URL).pathname, /^\/cti_soar_qa_/);
  const fixture = JSON.parse(readFileSync('../.omo/evidence/sicti-phase3a-qa-fixture.json', 'utf8'));
  const prisma = new PrismaClient();
  const moduleRef = await Test.createTestingModule({ imports: [ConfigModule.forRoot({ isGlobal: true }), AuthModule, PlaybookModule] }).compile();
  const app = moduleRef.createNestApplication({ logger: false });
  await app.listen(0, '127.0.0.1');
  const api = `http://127.0.0.1:${app.getHttpServer().address().port}`;
  try {
    const tokens = {};
    for (const key of ['initiator', 'approver', 'reader', 'outsider']) tokens[key] = await createAccessToken(prisma, fixture[key].id, process.env.JWT_ACCESS_SECRET);
    const request = (path, token, body) => fetch(`${api}/playbooks${path}`, { method: body === undefined ? 'GET' : 'POST', headers: { authorization: `Bearer ${token}`, 'Content-Type': 'application/json' }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
    const post = (path, token, body = {}) => request(path, token, body);
    const payload = { alertId: fixture.alertId, caseId: fixture.caseId, idempotencyKey: randomUUID() };
    const eligible = await (await request('/eligible-alerts', tokens.initiator)).json();
    assert.ok(eligible.some(row => row.alertId === fixture.alertId && row.domain === fixture.domain));
    assert.deepEqual(await (await request('/eligible-alerts', tokens.outsider)).json(), []);
    assert.equal((await post('/runs', '', payload)).status, 401);
    assert.equal((await post('/runs', tokens.reader, payload)).status, 403);
    assert.equal((await post('/runs', tokens.outsider, payload)).status, 404);
    const createdResponse = await post('/runs', tokens.initiator, payload);
    assert.equal(createdResponse.status, 201, await createdResponse.clone().text());
    const created = await createdResponse.json();
    assert.equal(created.status, 'PENDING_CONFIRMATION');
    assert.equal(created.domain, fixture.domain);
    assert.equal(created.caseId, fixture.caseId);
    assert.equal((await (await post('/runs', tokens.initiator, payload)).json()).id, created.id);
    assert.equal((await post('/runs', tokens.initiator, { ...payload, caseId: 'different-case' })).status, 409);
    assert.equal((await post(`/runs/${created.id}/execute`, tokens.initiator)).status, 409);
    const reason = 'Confirmed matched domain and source evidence in isolated QA.';
    const confirmed = await (await post(`/runs/${created.id}/decisions`, tokens.initiator, { kind: 'CONFIRM', reason })).json();
    assert.equal(confirmed.status, 'PENDING_APPROVAL');
    assert.equal((await post(`/runs/${created.id}/decisions`, tokens.initiator, { kind: 'APPROVE', reason })).status, 403);
    assert.equal((await post(`/runs/${created.id}/decisions`, tokens.reader, { kind: 'APPROVE', reason })).status, 403);
    const approved = await (await post(`/runs/${created.id}/decisions`, tokens.approver, { kind: 'APPROVE', reason })).json();
    assert.equal(approved.status, 'APPROVED');
    process.env.SICTI_SOAR_QA_ENABLED = 'true';
    process.env.SICTI_ISOLATED_QA = 'true';
    const executedResponse = await post(`/runs/${created.id}/execute`, tokens.initiator);
    assert.equal(executedResponse.status, 201, await executedResponse.clone().text());
    const executed = await executedResponse.json();
    assert.equal(executed.status, 'VERIFYING');
    assert.equal(executed.steps[0].receipts[0].result, 'SIMULATED');
    assert.equal(executed.steps[0].receipts[0].evidence.sandboxOnly, true);
    assert.equal((await post(`/runs/${created.id}/execute`, tokens.initiator)).status, 409);
    const verified = await (await post(`/runs/${created.id}/verify`, tokens.approver)).json();
    assert.equal(verified.status, 'VERIFIED');
    assert.equal(verified.steps[0].status, 'VERIFIED');
    assert.equal((await prisma.playbookReceipt.count({ where: { runId: created.id } })), 1);
    assert.equal((await prisma.alert.findUniqueOrThrow({ where: { id: fixture.alertId } })).status, 'OPEN');
    assert.equal((await prisma.case.findUniqueOrThrow({ where: { id: fixture.caseId } })).status, 'OPEN');
    assert.ok((await prisma.auditLog.count({ where: { tenantId: fixture.tenantId, metadata: { path: ['runId'], equals: created.id } } })) >= 4);
    assert.equal((await request(`/runs/${created.id}`, tokens.outsider)).status, 404);
    await prisma.playbookRun.update({ where: { id: created.id }, data: { tlp: 'RED' } });
    assert.equal((await request(`/runs/${created.id}`, tokens.reader)).status, 404);
    assert.ok(!(await (await request('/runs', tokens.reader)).json()).some(row => row.id === created.id));
    await assert.rejects(prisma.playbookReceipt.update({ where: { id: executed.steps[0].receipts[0].id }, data: { result: 'ALTERED' } }));
    const implicitCasePayload = { alertId: fixture.alertId, idempotencyKey: randomUUID() };
    const timeoutRun = await (await post('/runs', tokens.initiator, implicitCasePayload)).json();
    assert.equal(timeoutRun.caseId, fixture.caseId);
    assert.equal((await (await post('/runs', tokens.initiator, implicitCasePayload)).json()).id, timeoutRun.id);
    await post(`/runs/${timeoutRun.id}/decisions`, tokens.initiator, { kind: 'CONFIRM', reason });
    await post(`/runs/${timeoutRun.id}/decisions`, tokens.approver, { kind: 'APPROVE', reason });
    process.env.SICTI_SOAR_QA_FORCE_TIMEOUT = 'true';
    try {
      const failed = await (await post(`/runs/${timeoutRun.id}/execute`, tokens.initiator)).json();
      assert.equal(failed.status, 'FAILED');
      assert.equal(failed.steps[0].receipts[0].result, 'TIMEOUT');
      const retried = await (await post(`/runs/${timeoutRun.id}/retry`, tokens.approver)).json();
      assert.equal(retried.status, 'APPROVED');
    } finally { delete process.env.SICTI_SOAR_QA_FORCE_TIMEOUT; }
    const succeeded = await (await post(`/runs/${timeoutRun.id}/execute`, tokens.initiator)).json();
    assert.equal(succeeded.status, 'VERIFYING');
    assert.equal(succeeded.steps[0].attemptCount, 2);
    assert.equal((await prisma.playbookReceipt.count({ where: { runId: timeoutRun.id } })), 2);
    const indicator = await prisma.indicator.findFirstOrThrow({ where: { tenantId: fixture.tenantId, value: fixture.domain } });
    await prisma.indicator.update({ where: { id: indicator.id }, data: { suppressionKind: 'FALSE_POSITIVE' } });
    assert.deepEqual(await (await request('/eligible-alerts', tokens.initiator)).json(), []);
    await prisma.indicator.update({ where: { id: indicator.id }, data: { suppressionKind: null } });
    await prisma.case.delete({ where: { id: fixture.caseId } });
    const detached = await prisma.playbookRun.findUniqueOrThrow({ where: { id: created.id } });
    assert.equal(detached.caseId, null);
    assert.equal(detached.tenantId, fixture.tenantId);
  } finally { await app.close(); await prisma.$disconnect(); }
});

const assert = require('node:assert/strict');
const test = require('node:test');
const { randomUUID } = require('node:crypto');
require('dotenv').config();
const { PrismaClient } = require('@prisma/client');
const { JwtService } = require('@nestjs/jwt');
const base = 'http://localhost:3001';
const jwt = new JwtService();
const token = id => jwt.sign({ sub: id }, { secret: process.env.JWT_ACCESS_SECRET });
const request = (path, id, method = 'GET', body) => fetch(`${base}${path}`, { method, headers: { ...(id ? { Authorization: `Bearer ${token(id)}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });

test('real HTTP guards enforce ASM, Case and tenant boundaries', { timeout: 60000 }, async () => {
  const prisma = new PrismaClient();
  const marker = randomUUID();
  let tenantId;
  let otherId;
  let adminId;
  let deniedId;
  let userId;
  let superId;
  let caseId;
  try {
    const asm = await prisma.appModule.findUniqueOrThrow({ where: { slug: 'attack-surface-management' } });
    const cases = await prisma.appModule.findUniqueOrThrow({ where: { slug: 'case-management' } });
    const tenant = await prisma.tenant.create({ data: { name: `HTTP QA ${marker}`, slug: `http-qa-${marker}` } });
    tenantId = tenant.id;
    const other = await prisma.tenant.create({ data: { name: `HTTP Other ${marker}`, slug: `http-other-${marker}` } });
    otherId = other.id;
    const subscription = await prisma.tenantSubscription.create({ data: { tenantId, isCustom: true, billingCycle: 'MONTHLY', priceMonthly: 0, status: 'ACTIVE', renewalAt: new Date(Date.now() + 86_400_000) } });
    await prisma.tenantCustomModule.createMany({ data: [{ subscriptionId: subscription.id, moduleId: asm.id }, { subscriptionId: subscription.id, moduleId: cases.id }] });
    const policy = await prisma.tenantModule.create({ data: { tenantId, moduleId: asm.id, isEnabled: true } });
    await prisma.moduleRoleAccess.create({ data: { tenantModuleId: policy.id, role: 'ADMIN', isAllowed: true } });
    const admin = await prisma.user.create({ data: { email: `asm-admin-${marker}@example.invalid`, name: 'ASM Admin', passwordHash: 'not-a-login', role: 'ADMIN', tenantId } });
    adminId = admin.id;
    const denied = await prisma.user.create({ data: { email: `asm-denied-${marker}@example.invalid`, name: 'Denied Admin', passwordHash: 'not-a-login', role: 'ADMIN', tenantId } });
    deniedId = denied.id;
    const regular = await prisma.user.create({ data: { email: `asm-user-${marker}@example.invalid`, name: 'ASM User', passwordHash: 'not-a-login', role: 'USER', tenantId } });
    userId = regular.id;
    await prisma.moduleRoleAccess.create({ data: { tenantModuleId: policy.id, role: 'USER', isAllowed: true } });
    const superAdmin = await prisma.user.create({ data: { email: `asm-super-${marker}@example.invalid`, name: 'ASM Super', passwordHash: 'not-a-login', role: 'SUPER_ADMIN' } });
    superId = superAdmin.id;
    await prisma.userModuleAccess.create({ data: { userId: adminId, tenantId, moduleId: asm.id, featureKeys: ['asset-management'] } });
    await prisma.userModuleAccess.create({ data: { userId, tenantId, moduleId: asm.id, featureKeys: ['asset-management'] } });
    const asset = await prisma.asset.create({ data: { tenantId, name: 'HTTP IP', type: 'IP_ADDRESS', value: '192.0.2.58' } });
    const alert = await prisma.alert.create({ data: { tenantId, assetId: asset.id, source: 'ASM', sourceKey: `http:${marker}`, title: 'HTTP QA Alert', severity: 'HIGH' } });
    const route = `/attack-surface/assets/${asset.id}/alerts`;
    const postureRoute = `/attack-surface/assets/${asset.id}/risk-posture`;
    const backfillRoute = '/attack-surface/alerts/backfill';
    assert.equal((await request(postureRoute)).status, 401);
    assert.equal((await request(backfillRoute, undefined, 'POST')).status, 401);
    assert.equal((await request(postureRoute, deniedId)).status, 403);
    assert.equal((await request(backfillRoute, deniedId, 'POST')).status, 403);
    assert.equal((await request(backfillRoute, userId, 'POST')).status, 403);
    const emptyHistory = await request(postureRoute, adminId);
    assert.equal(emptyHistory.status, 200);
    assert.equal((await emptyHistory.json()).current, null);
    assert.equal((await request(`${postureRoute}?tenantId=${otherId}`, adminId)).status, 200);
    assert.equal((await request(`${backfillRoute}?tenantId=${otherId}`, adminId, 'POST')).status, 201);
    assert.equal((await request(`/attack-surface/assets/${asset.id}/risk-posture?tenantId=${otherId}`, superId)).status, 404);
    assert.equal((await request(postureRoute, superId)).status, 400);
    assert.equal((await request(`${postureRoute}?tenantId=${tenantId}`, superId)).status, 200);
    assert.equal((await request(backfillRoute, superId, 'POST')).status, 400);
    assert.equal((await request(`${backfillRoute}?tenantId=${tenantId}`, superId, 'POST')).status, 201);
    assert.equal((await request(route)).status, 401);
    assert.equal((await request(route, deniedId)).status, 403);
    assert.equal((await request(route, adminId)).status, 200);
    assert.equal((await request(route, userId)).status, 200);
    assert.equal((await request(`/cases/from-asm-alert/${alert.id}`, userId, 'POST', {})).status, 403);
    assert.equal((await request(`/cases/from-asm-alert/${alert.id}`, adminId, 'POST', {})).status, 403);
    assert.equal((await request(`${route}?tenantId=${otherId}`, superId)).status, 404);
    assert.equal((await request(route, superId)).status, 400);
    assert.equal((await request(`${route}?tenantId=${tenantId}`, superId)).status, 200);
    assert.equal((await request(`${route}/${alert.id}/acknowledge`, adminId, 'PATCH')).status, 200);
    const created = await request(`/cases/from-asm-alert/${alert.id}`, superId, 'POST', { tenantId });
    assert.equal(created.status, 201);
    caseId = (await created.json()).id;
    const repeated = await request(`/cases/from-asm-alert/${alert.id}`, superId, 'POST', { tenantId });
    assert.equal((await repeated.json()).id, caseId);
    assert.equal((await request(`/cases/from-asm-alert/${alert.id}`, superId, 'POST', { tenantId: otherId })).status, 404);
  } finally {
    if (caseId) await prisma.case.delete({ where: { id: caseId } });
    if (adminId) await prisma.user.delete({ where: { id: adminId } });
    if (deniedId) await prisma.user.delete({ where: { id: deniedId } });
    if (userId) await prisma.user.delete({ where: { id: userId } });
    if (superId) await prisma.user.delete({ where: { id: superId } });
    if (tenantId) await prisma.tenant.delete({ where: { id: tenantId } });
    if (otherId) await prisma.tenant.delete({ where: { id: otherId } });
    await prisma.$disconnect();
  }
});

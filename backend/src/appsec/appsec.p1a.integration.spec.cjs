const assert = require('node:assert/strict');
const test = require('node:test');
const { randomUUID } = require('node:crypto');
const { Test } = require('@nestjs/testing');
const { ValidationPipe } = require('@nestjs/common');
const { JwtService } = require('@nestjs/jwt');
const { PrismaClient } = require('@prisma/client');
const { AppSecModule } = require('../../dist/src/appsec/appsec.module');
const { createAccessToken } = require('../auth/integration-session.cjs');

test('P1-A authenticated lifecycle preserves V1 and enforces tenant and revision', { timeout: 120000 }, async () => {
  const prisma = new PrismaClient();
  const marker = randomUUID();
  const previousSecret = process.env.JWT_ACCESS_SECRET;
  const previousRollout = process.env.APPSEC_V2_TRIAGE_ENABLED;
  process.env.JWT_ACCESS_SECRET = marker;
  process.env.APPSEC_V2_TRIAGE_ENABLED = 'true';
  const moduleRef = await Test.createTestingModule({ imports: [AppSecModule] }).compile();
  const app = moduleRef.createNestApplication({ logger: false });
  app.useGlobalPipes(new ValidationPipe({ whitelist: true, transform: true }));
  try {
    await app.listen(0, '127.0.0.1');
    const base = `http://127.0.0.1:${app.getHttpServer().address().port}`;
    const a = await prisma.tenant.create({ data: { name: 'P1A A', slug: `p1a-a-${marker}` } });
    const b = await prisma.tenant.create({ data: { name: 'P1A B', slug: `p1a-b-${marker}` } });
    const module = await prisma.appModule.upsert({ where: { slug: 'appsec-posture' }, update: {}, create: { slug: 'appsec-posture', name: 'AppSec', description: 'QA module', category: 'APPSEC', features: { create: [{ key: 'finding-management', name: 'Finding Management' }] } } });
    await prisma.tenantSubscription.create({ data: { tenantId: a.id, isCustom: true, billingCycle: 'MONTHLY', priceMonthly: 0, renewalAt: new Date(Date.now() + 86400000), status: 'ACTIVE', customModules: { create: { moduleId: module.id } } } });
    await prisma.tenantModule.create({ data: { tenantId: a.id, moduleId: module.id, access: { create: [{ role: 'ADMIN', isAllowed: true }, { role: 'USER', isAllowed: true }] } } });
    const admin = await prisma.user.create({ data: { name: 'Admin', email: `p1a-admin-${marker}@example.test`, passwordHash: 'unused', role: 'ADMIN', tenantId: a.id } });
    const user = await prisma.user.create({ data: { name: 'User', email: `p1a-user-${marker}@example.test`, passwordHash: 'unused', role: 'USER', tenantId: a.id } });
    const foreign = await prisma.user.create({ data: { name: 'Foreign', email: `p1a-foreign-${marker}@example.test`, passwordHash: 'unused', role: 'USER', tenantId: b.id } });
    await prisma.userModuleAccess.create({ data: { userId: admin.id, tenantId: a.id, moduleId: module.id, featureKeys: ['finding-management'] } });
    await prisma.userModuleAccess.create({ data: { userId: user.id, tenantId: a.id, moduleId: module.id, featureKeys: ['finding-management'] } });
    const application = await prisma.application.create({ data: { tenantId: a.id, name: 'P1A app' } });
    const tokens = new Map(await Promise.all([admin,user].map(async person => [person.id, await createAccessToken(prisma, person.id, marker)])));
    async function call(actor, path, method = 'GET', body) {
      const response = await fetch(base + path, { method, headers: { 'content-type': 'application/json', ...(actor ? { authorization: `Bearer ${tokens.get(actor.id)}` } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      const text = await response.text();
      return { status: response.status, body: text ? JSON.parse(text) : null };
    }
    const made = await call(admin, '/appsec/findings', 'POST', { applicationId: application.id, title: 'Triage issue', severity: 'HIGH' });
    assert.equal(made.status, 201);
    const path = `/appsec/findings/${made.body.id}`;
    assert.equal(made.body.workflowVersion, 1);
    assert.equal((await call(admin, path, 'PATCH', { status: 'RESOLVED', resolution: 'V1 decision' })).status, 200);
    assert.equal((await call(admin, path, 'PATCH', { status: 'OPEN' })).status, 200);
    assert.equal((await call(user, `${path}/lifecycle/activate`, 'POST', { expectedRevision: 0, reason: 'Review' })).status, 403);
    assert.equal((await call(null, `${path}/lifecycle/activate`, 'POST', { expectedRevision: 0, reason: 'Review' })).status, 401);
    const key = randomUUID();
    const activate = { expectedRevision: 0, reason: 'Start V2 triage', requestKey: key };
    const [active, concurrentRetry] = await Promise.all([call(admin, `${path}/lifecycle/activate`, 'POST', activate), call(admin, `${path}/lifecycle/activate`, 'POST', activate)]);
    assert.equal(active.status, 201, JSON.stringify(active.body));
    assert.equal(concurrentRetry.status, 201, JSON.stringify(concurrentRetry.body));
    assert.equal(active.body.finding.workflowVersion, 2);
    assert.equal(concurrentRetry.body.event.id, active.body.event.id);
    assert.equal((await call(admin, `${path}/lifecycle/activate`, 'POST', { ...activate, reason: 'Different' })).status, 409);
    assert.equal((await call(admin, path, 'PATCH', { status: 'RESOLVED', resolution: 'Bypass' })).status, 409);
    assert.equal((await call(admin, path, 'PATCH', { title: 'Updated', expectedRevision: 0 })).status, 409);
    assert.equal((await call(admin, `${path}/lifecycle/priority`, 'POST', { expectedRevision: 1, priority: 'CRITICAL', rationale: 'Asset impact' })).status, 400);
    const rejected = await call(admin, `${path}/lifecycle/validate`, 'POST', { expectedRevision: 1, decision: 'REJECTED', rationale: 'Needs detail' });
    assert.equal(rejected.status, 201, JSON.stringify(rejected.body));
    const valid = await call(admin, `${path}/lifecycle/validate`, 'POST', { expectedRevision: 2, decision: 'VALID', rationale: 'Confirmed' });
    assert.equal(valid.status, 201, JSON.stringify(valid.body));
    const priority = await call(admin, `${path}/lifecycle/priority`, 'POST', { expectedRevision: 3, priority: 'CRITICAL', rationale: 'High impact' });
    assert.equal(priority.status, 201, JSON.stringify(priority.body));
    assert.equal(priority.body.finding.severity, 'HIGH');
    assert.equal((await call(admin, `${path}/lifecycle/assign`, 'POST', { expectedRevision: 4, assigneeId: foreign.id })).status, 404);
    const assigned = await call(admin, `${path}/lifecycle/assign`, 'POST', { expectedRevision: 4, assigneeId: user.id });
    assert.equal(assigned.status, 201, JSON.stringify(assigned.body));
    assert.equal(assigned.body.finding.assigneeId, user.id);
    assert.equal((await call(admin, `${path}/lifecycle/assign`, 'POST', { expectedRevision: 4, assigneeId: admin.id, reason: 'Rotate' })).status, 409);
    const userHistory = await call(user, `${path}/lifecycle/events`);
    assert.equal(userHistory.body.total, 5);
    assert.ok(userHistory.body.items.every(event => event.actorName === admin.name));
    const userFinding = await call(user, path);
    assert.equal(userFinding.body.assigneeName, user.name);
    assert.equal(Object.hasOwn(userFinding.body, 'assignee'), false);
    assert.equal(await prisma.appSecFindingActionEvent.count({ where: { findingId: made.body.id } }), 5);
    assert.equal(await prisma.auditLog.count({ where: { tenantId: a.id, action: { startsWith: 'APPSEC_FINDING_' } } }), 8);
    const inactive = await prisma.user.create({ data: { name: 'Inactive', email: `p1a-inactive-${marker}@example.test`, passwordHash: 'unused', role: 'USER', tenantId: a.id, isActive: false } });
    assert.equal((await call(admin, `${path}/lifecycle/assign`, 'POST', { expectedRevision: 5, assigneeId: inactive.id, reason: 'Reassign' })).status, 404);
    const metadata = await call(admin, path, 'PATCH', { expectedRevision: 5, title: 'Updated V2 title' });
    assert.equal(metadata.status, 200, JSON.stringify(metadata.body));
    assert.equal(metadata.body.revision, 6);
    const lateRetry = await call(admin, `${path}/lifecycle/activate`, 'POST', activate);
    assert.equal(lateRetry.status, 201);
    assert.equal(lateRetry.body.finding.revision, 1);
    assert.equal(lateRetry.body.event.id, active.body.event.id);
    assert.equal((await call(admin, path, 'PATCH', { expectedRevision: 6, priority: 'LOW' })).status, 409);
    process.env.APPSEC_V2_TRIAGE_ENABLED = 'false';
    assert.equal((await call(admin, `${path}/lifecycle/priority`, 'POST', { expectedRevision: 6, priority: 'HIGH', rationale: 'Disabled' })).status, 403);
    process.env.APPSEC_V2_TRIAGE_ENABLED = 'true';
    await prisma.$executeRawUnsafe("CREATE FUNCTION p1a_reject_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.\"action\" = 'APPSEC_FINDING_PRIORITY_SET' THEN RAISE EXCEPTION 'forced audit failure'; END IF; RETURN NEW; END $$");
    await prisma.$executeRawUnsafe('CREATE TRIGGER p1a_reject_audit_trigger BEFORE INSERT ON "AuditLog" FOR EACH ROW EXECUTE FUNCTION p1a_reject_audit()');
    try {
      assert.equal((await call(admin, `${path}/lifecycle/priority`, 'POST', { expectedRevision: 6, priority: 'MEDIUM', rationale: 'Rollback check' })).status, 500);
      assert.equal((await prisma.appSecFinding.findUniqueOrThrow({ where: { id: made.body.id } })).revision, 6);
      assert.equal(await prisma.appSecFindingActionEvent.count({ where: { findingId: made.body.id } }), 5);
    } finally {
      await prisma.$executeRawUnsafe('DROP TRIGGER p1a_reject_audit_trigger ON "AuditLog"');
      await prisma.$executeRawUnsafe('DROP FUNCTION p1a_reject_audit()');
    }
    const root = await prisma.user.create({ data: { name: 'Root', email: `p1a-root-${marker}@example.test`, passwordHash: 'unused', role: 'SUPER_ADMIN' } });
    tokens.set(root.id, await createAccessToken(prisma, root.id, marker));
    assert.equal((await call(root, `${path}/lifecycle/priority`, 'POST', { expectedRevision: 6, priority: 'MEDIUM', rationale: 'No tenant' })).status, 400);
    assert.equal((await call(root, `${path}/lifecycle/priority?tenantId=${b.id}`, 'POST', { expectedRevision: 6, priority: 'MEDIUM', rationale: 'No entitlement' })).status, 403);
    assert.equal((await call(root, `${path}/lifecycle/priority?tenantId=${a.id}`, 'POST', { expectedRevision: 6, priority: 'MEDIUM', rationale: 'Selected tenant' })).status, 201);
    const rootHistory = await call(user, `${path}/lifecycle/events`);
    assert.equal(rootHistory.body.items[0].actorName, root.name);
    await prisma.user.update({ where: { id: admin.id }, data: { isActive: false } });
    const deactivatedActorHistory = await call(user, `${path}/lifecycle/events`);
    assert.equal(deactivatedActorHistory.body.items[1].actorName, `${admin.name} (inactive)`);
    await prisma.user.update({ where: { id: user.id }, data: { isActive: false } });
    const inactiveAssigneeFinding = await call(root, `${path}?tenantId=${a.id}`);
    assert.equal(inactiveAssigneeFinding.body.assigneeName, null);
    assert.equal(Object.hasOwn(inactiveAssigneeFinding.body, 'assignee'), false);
  } finally {
    await app.close();
    await prisma.$disconnect();
    if (previousSecret === undefined) delete process.env.JWT_ACCESS_SECRET;
    else process.env.JWT_ACCESS_SECRET = previousSecret;
    if (previousRollout === undefined) delete process.env.APPSEC_V2_TRIAGE_ENABLED;
    else process.env.APPSEC_V2_TRIAGE_ENABLED = previousRollout;
  }
});

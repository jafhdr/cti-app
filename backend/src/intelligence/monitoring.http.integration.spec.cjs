require('reflect-metadata');
const assert = require('node:assert/strict');
const { test } = require('node:test');
const { randomUUID, createHash } = require('node:crypto');
const { readFileSync } = require('node:fs');
const { Test } = require('@nestjs/testing');
const { PrismaClient } = require('@prisma/client');
const { AuthModule } = require('../../dist/src/auth/auth.module');
const { CasesModule } = require('../../dist/src/cases/cases.module');
const { PrismaService } = require('../../dist/src/prisma.service');
const { MonitoringController } = require('../../dist/src/intelligence/monitoring.controller');
const { MonitoringService } = require('../../dist/src/intelligence/monitoring.service');
const { MonitoringLinksService } = require('../../dist/src/intelligence/monitoring-links.service');
const { MonitoringCollectorService } = require('../../dist/src/intelligence/monitoring-collector.service');
const { createAccessToken } = require('../auth/integration-session.cjs');

test('Given tenant-authorized synthetic sources, when observations are reviewed, then only safe scoped findings link to alert and case', { timeout: 90000 }, async () => {
  assert.equal(new URL(process.env.DATABASE_URL || '').pathname, '/cti_phase4a_qa_20261111');
  assert.equal(process.env.SICTI_MONITORING_QA_ENABLED, 'true');
  process.env.SICTI_MONITORING_IDENTITY_ACTIVE_VERSION = 'v1';
  process.env.SICTI_MONITORING_IDENTITY_KEY_V1 = Buffer.alloc(32, 7).toString('base64url');
  const fixture = JSON.parse(readFileSync('../.omo/evidence/sicti-phase4a-qa-fixture.json', 'utf8'));
  const prisma = new PrismaClient();
  const module = await Test.createTestingModule({ imports: [AuthModule, CasesModule], controllers: [MonitoringController], providers: [MonitoringService, MonitoringLinksService, MonitoringCollectorService, PrismaService] }).compile();
  const app = module.createNestApplication({ logger: false });
  try {
    await app.listen(0, '127.0.0.1');
    const origin = `http://127.0.0.1:${app.getHttpServer().address().port}`;
    const token = async user => createAccessToken(prisma, user.id, process.env.JWT_ACCESS_SECRET);
    const own = await token(fixture.own.users.admin);
    const reader = await token(fixture.own.users.reader);
    const foreign = await token(fixture.foreign.users.admin);
    async function call(path, method = 'GET', body, bearer = own) {
      const response = await fetch(`${origin}/intelligence/monitoring/${path}`, { method, headers: { authorization: `Bearer ${bearer}`, ...(body ? { 'content-type': 'application/json' } : {}) }, ...(body ? { body: JSON.stringify(body) } : {}) });
      return { status: response.status, body: await response.json() };
    }
    const watch = await call('watchlists', 'POST', { kind: 'DOMAIN', value: fixture.own.domain.toUpperCase(), assetId: fixture.own.assetId });
    assert.equal(watch.status, 201);
    assert.equal(watch.body.label, fixture.own.domain);
    assert.equal((await call('watchlists', 'POST', { kind: 'DOMAIN', value: fixture.own.domain })).status, 409);
    assert.equal((await call('watchlists', 'POST', { kind: 'DOMAIN', value: fixture.foreign.domain, assetId: fixture.foreign.assetId })).status, 404);
    assert.equal((await call('watchlists', 'POST', { kind: 'BRAND', value: 'Acme' }, reader)).status, 403);
    const identity = `analyst@${fixture.own.domain}`;
    const identityWatch = await call('watchlists', 'POST', { kind: 'IDENTITY_HASH', value: identity });
    assert.equal(identityWatch.status, 201);
    assert.equal(JSON.stringify(identityWatch.body).includes('analyst'), false);
    const source = await call('sources', 'POST', { catalogSourceId: fixture.own.sourceId, providerKey: `qa-fixture-${randomUUID()}`, retentionDays: 30 });
    assert.equal(source.status, 201);
    assert.equal((await call('sources', 'POST', { catalogSourceId: fixture.own.sourceId, providerKey: source.body.providerKey, retentionDays: 30 })).status, 409);
    assert.equal((await call('sources', 'POST', { catalogSourceId: fixture.foreign.sourceId, providerKey: `qa-fixture-${randomUUID()}`, retentionDays: 30 })).status, 400);
    const eventKey = randomUUID();
    const observation = { sourceId: source.body.id, providerEventKey: eventKey, kind: 'PHISHING_DOMAIN', domain: fixture.own.domain, metadataCategory: 'PHISHING_SIGNAL', evidenceRef: 'qa://fixture/evidence-1', evidenceDigest: createHash('sha256').update('synthetic evidence').digest('hex'), observedAt: new Date().toISOString(), tlp: 'AMBER' };
    const ingested = await call('observations', 'POST', observation);
    assert.equal(ingested.status, 201);
    assert.equal(ingested.body.matches.length, 1);
    assert.equal((await call('observations', 'POST', observation)).body.id, ingested.body.id);
    assert.equal((await call('observations', 'POST', { ...observation, evidenceDigest: 'f'.repeat(64) })).status, 409);
    assert.equal((await call('observations', 'POST', { ...observation, metadataCategory: 'DATASET_MENTION' })).status, 400);
    assert.equal((await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), domain: 'unrelated.test' })).body.matches.length, 0);
    const credential = await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), kind: 'CREDENTIAL_EXPOSURE', domain: undefined, identity, metadataCategory: 'ACCOUNT_PRESENT' });
    assert.equal(credential.status, 201);
    assert.equal(credential.body.matches.length, 1);
    assert.equal(JSON.stringify(credential.body).includes('analyst'), false);
    const corporate = await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), kind: 'CORPORATE_DATA_EXPOSURE', metadataCategory: 'DATASET_MENTION' });
    assert.equal(corporate.status, 201);
    assert.equal(corporate.body.matches.length, 1);
    const expired = await call('watchlists', 'POST', { kind: 'BRAND', value: `expired${randomUUID().slice(0, 8)}` });
    assert.equal(expired.status, 201);
    await prisma.monitoringWatchlist.update({ where: { id: expired.body.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    const noExpiredMatch = await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), domain: `${expired.body.label}-login.test` });
    assert.equal(noExpiredMatch.body.matches.length, 0);
    assert.equal((await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), password: 'never-store' })).status, 400);
    assert.equal((await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), evidenceRef: 'https://unsafe.test/token' })).status, 400);
    const findingId = ingested.body.matches[0].finding.id;
    assert.equal((await call(`findings/${findingId}`, 'GET', undefined, foreign)).status, 404);
    assert.equal((await call(`findings/${findingId}`, 'GET', undefined, reader)).status, 200);
    assert.equal((await call(`findings/${findingId}/reviews`, 'POST', { status: 'UNDER_REVIEW', expectedStatus: 'NEW', reason: 'Investigating synthetic observation' }, reader)).status, 403);
    assert.equal((await call(`findings/${findingId}/reviews`, 'POST', { status: 'UNDER_REVIEW', expectedStatus: 'NEW', reason: 'Investigating synthetic observation' })).status, 201);
    assert.equal((await call(`findings/${findingId}/reviews`, 'POST', { status: 'CONFIRMED', expectedStatus: 'UNDER_REVIEW', reason: 'Domain match and source provenance checked' })).status, 201);
    assert.equal((await call(`findings/${findingId}/reviews`, 'POST', { status: 'CONFIRMED', expectedStatus: 'UNDER_REVIEW', reason: 'Duplicate stale review' })).status, 409);
    const alert = await call(`findings/${findingId}/alert`, 'POST', {});
    assert.equal(alert.status, 201);
    assert.equal(alert.body.source, 'MONITORING');
    const linkedCase = await call(`findings/${findingId}/case`, 'POST', { createCase: true });
    assert.equal(linkedCase.status, 201);
    assert.equal(linkedCase.body.tenantId, fixture.own.tenantId);
    const detail = await call(`findings/${findingId}`);
    assert.equal(detail.body.alertId, alert.body.id);
    assert.equal(detail.body.caseId, linkedCase.body.id);
    assert.equal(detail.body.reviews.length, 2);
    assert.equal(JSON.stringify(detail.body).includes('identityHash'), false);
    const red = await call('observations', 'POST', { ...observation, providerEventKey: randomUUID(), tlp: 'RED' });
    assert.equal(red.status, 201);
    assert.equal((await call(`findings/${red.body.matches[0].finding.id}`, 'GET', undefined, reader)).status, 404);
    const falsePositive = await call(`findings/${red.body.matches[0].finding.id}/reviews`, 'POST', { status: 'FALSE_POSITIVE', expectedStatus: 'NEW', reason: 'Synthetic false positive test' });
    assert.equal(falsePositive.status, 201);
    assert.equal((await call(`findings/${red.body.matches[0].finding.id}/reviews`, 'POST', { status: 'UNDER_REVIEW', expectedStatus: 'FALSE_POSITIVE', reason: 'Must remain dismissed' })).status, 409);
    await prisma.monitoringObservation.update({ where: { id: red.body.id }, data: { expiresAt: new Date(Date.now() - 1000) } });
    assert.equal((await call(`findings/${red.body.matches[0].finding.id}`)).status, 404);
    assert.ok((await app.get(MonitoringService).scrubExpired()) >= 1);
    const scrubbed = await prisma.monitoringObservation.findUniqueOrThrow({ where: { id: red.body.id } });
    assert.equal(scrubbed.domain, null);
    assert.equal(scrubbed.identityHash, null);
    assert.equal(scrubbed.evidenceRef, 'qa://expired/redacted');
    process.env.SICTI_MONITORING_QA_ENABLED = 'false';
    try { assert.equal((await call('observations', 'POST', { ...observation, providerEventKey: randomUUID() })).status, 403); }
    finally { process.env.SICTI_MONITORING_QA_ENABLED = 'true'; }
    assert.equal((await prisma.monitoringObservation.count({ where: { tenantId: fixture.own.tenantId, providerEventKey: eventKey } })), 1);
    await prisma.case.delete({ where: { id: linkedCase.body.id } });
    await prisma.alert.delete({ where: { id: alert.body.id } });
    await prisma.asset.delete({ where: { id: fixture.own.assetId } });
    const detached = await prisma.monitoringFinding.findUniqueOrThrow({ where: { id: findingId } });
    assert.equal(detached.caseId, null);
    assert.equal(detached.alertId, null);
    assert.equal((await prisma.monitoringWatchlist.findUniqueOrThrow({ where: { id: watch.body.id } })).assetId, null);
    const catalogName = (await prisma.intelligenceSource.findUniqueOrThrow({ where: { id: fixture.own.sourceId } })).name;
    await prisma.intelligenceSource.delete({ where: { id: fixture.own.sourceId } });
    const detachedSource = await prisma.monitoringSource.findUniqueOrThrow({ where: { id: source.body.id } });
    assert.equal(detachedSource.catalogSourceId, null);
    assert.equal(detachedSource.catalogName, catalogName);
    const sourcesAfterDetach = await call('sources');
    assert.equal(sourcesAfterDetach.status, 200);
    assert.equal(sourcesAfterDetach.body.find(item => item.id === source.body.id).catalogSource.status, 'INACTIVE');
    assert.equal((await call('observations', 'POST', { ...observation, providerEventKey: randomUUID() })).status, 404);
  } finally { await app.close(); await prisma.$disconnect(); }
});
